export function exampleSuggestions(engine,example,start,end=start){
  const target=exampleWordAt(example,start,end);if(!target||target.input.length>512)return null;
  const previousWords=[];let cursor=0;
  for(const token of exampleTokens(example)){
    if(token.start>=target.start)break;
    if(/[.!?។\n\r]/.test(example.romanized.slice(cursor,token.start)))previousWords.length=0;
    if(token.word)previousWords.push(token.word);else previousWords.length=0;
    cursor=token.end;
  }
  if(/[.!?។\n\r]/.test(example.romanized.slice(cursor,target.start)))previousWords.length=0;
  const result=engine.suggest(target.input,{language:'khmer',conversion:true,soundMap:true,completion:true,correction:false,previousWords:previousWords.slice(-63)});
  return {target,result};
}
export function chooseExampleWord(engine,example,target,candidate){
  const fresh=exampleSuggestions(engine,example,target.start,target.end);
  const chosen=fresh?.target.input===target.input&&fresh.target.start===target.start&&fresh.target.end===target.end
    &&fresh.result.candidates.find(item=>JSON.stringify(item)===JSON.stringify(candidate));
  if(!chosen?.khmer||!/^[\u1780-\u17ff]+$/.test(chosen.khmer))throw new Error('This word changed. Select it again.');
  const suggested=chosen.correction??chosen.completion;
  const input=suggested&&suggested.toLowerCase()!==target.input.toLowerCase()?suggested:target.input;
  if(!/^[a-z]+(?:[ '\-][a-z]+)*$/i.test(input))throw new Error('This word changed. Select it again.');
  const romanized=example.romanized.slice(0,target.start)+input+example.romanized.slice(target.end),end=target.start+input.length;
  if(romanized.length>MAX_EXAMPLE_TEXT)throw new Error('Keep the paragraph within 20,000 characters.');
  const spans=retainedSpans(example,romanized,{start:target.start,oldEnd:target.end,newEnd:end})
    .filter(span=>span.end<=target.start||span.start>=end);
  spans.push({start:target.start,end,input,word:chosen.khmer});
  return composeExample(romanized,exampleTokens({romanized,spans})).value;
}
export function convertExample(engine,previous,romanized){
  if(romanized.length>MAX_EXAMPLE_TEXT)throw new Error('Keep the paragraph within 20,000 characters.');
  const tokens=exampleTokens({romanized,spans:retainedSpans(previous,romanized)}),previousWords=[];let cursor=0;
  for(const token of tokens){
    if(/[.!?។\n\r]/.test(romanized.slice(cursor,token.start)))previousWords.length=0;
    if(!token.word&&token.input.length<=512){
      const result=engine.suggest(token.input,{language:'khmer',conversion:true,soundMap:true,completion:false,correction:false,previousWords:previousWords.slice(-63)});
      const choice=result.exactCandidates?.[0]??result.candidates.find(candidate=>!candidate.completion||candidate.completion.toLowerCase()===token.input.toLowerCase());
      token.word=choice?.khmer;
    }
    if(token.word)previousWords.push(token.word);else previousWords.length=0;
    cursor=token.end;
  }
  return composeExample(romanized,tokens).value;
}

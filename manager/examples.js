export function exampleParagraph(topic){
  const sentences=topic.sentences.map(sentence=>{
    const question=sentence.at(-1)==='?',words=question?sentence.slice(0,-1):sentence;
    return {romanized:words.map(word=>exampleWords[word]).join(' ')+(question?'?':'.'),khmer:words.join('')+(question?'?':'។')};
  });
  return {romanized:sentences.map(sentence=>sentence.romanized).join(' '),khmer:sentences.map(sentence=>sentence.khmer).join(' ')};
}

export function examplePage(hash,language,customTopics=[]){
  if(language!=='khmer'||!/^#words\/examples(?:\/[^/]*)?$/.test(hash))return null;
  if(hash==='#words/examples/new')return {topic:{id:'new',title:'Add example',custom:true,isNew:true}};
  return {topic:[...exampleTopics,...customTopics].find(topic=>hash===`#words/examples/${topic.id}`)??null};
}

export const EXAMPLES_KEY='kmeow-manager-examples-v1';
export const MAX_EXAMPLE_TEXT=20000;
const inputWords=/[a-z]+(?:['-][a-z]+)*/gi;
export function initialExample(topic){
  if(topic.custom)return {romanized:'',khmer:'',spans:[]};
  const paragraph=exampleParagraph(topic),words=topic.sentences.flat().filter(word=>word!=='?');
  const spans=[...paragraph.romanized.matchAll(inputWords)].map((match,index)=>({start:match.index,end:match.index+match[0].length,input:match[0],word:words[index]}));
  return {...paragraph,spans};
}
function savedExamples(storage){
  const text=storage.getItem(EXAMPLES_KEY);
  if(text===null)return {format:'kmeow-example-edits-v1',topics:{}};
  if(text.length>2*1024*1024)throw new Error('Saved examples are too large to read.');
  const data=JSON.parse(text);
  if(data?.format!=='kmeow-example-edits-v1'||!data.topics||typeof data.topics!=='object'||Array.isArray(data.topics))throw new Error('Saved examples could not be read.');
  const custom=data.customTopics??[];
  if(!Array.isArray(custom)||custom.some(topic=>!topic||!/^custom-[a-z0-9-]{1,80}$/.test(topic.id)
    ||typeof topic.title!=='string'||!topic.title.trim()||topic.title.length>120)
    ||new Set(custom.map(topic=>topic.id)).size!==custom.length)throw new Error('Saved examples could not be read.');
  return data;
}
export function customExampleTopics(storage){
  return (savedExamples(storage).customTopics??[]).map(({id,title})=>({id,title,custom:true}));
}
function writeExamples(storage,saved){
  const text=JSON.stringify(saved);
  if(text.length>2*1024*1024)throw new Error('Saved examples are too large to read.');
  storage.setItem(EXAMPLES_KEY,text);
}
const paragraphValue=value=>({romanized:value.romanized,khmer:value.khmer,spans:value.spans});
function validExample(value){
  return value&&typeof value.romanized==='string'&&value.romanized.length<=MAX_EXAMPLE_TEXT
    &&typeof value.khmer==='string'&&value.khmer.length<=MAX_EXAMPLE_TEXT*10&&Array.isArray(value.spans)
    &&value.spans.every(span=>Number.isInteger(span.start)&&Number.isInteger(span.end)&&span.start>=0&&span.end>span.start
      &&typeof span.input==='string'&&value.romanized.slice(span.start,span.end)===span.input&&typeof span.word==='string'&&/^[\u1780-\u17ff]+$/.test(span.word));
}
export function loadExample(topic,storage){
  const saved=savedExamples(storage).topics[topic.id];
  if(saved===undefined&&!topic.custom)return initialExample(topic);
  if(!validExample(saved))throw new Error('This saved example could not be read.');
  return saved;
}
export function saveExample(topic,value,storage){
  if(!validExample(value))throw new Error('This example could not be saved.');
  const saved=savedExamples(storage);
  if(![...exampleTopics,...(saved.customTopics??[])].some(item=>item.id===topic.id))throw new Error('This example could not be saved.');
  const paragraph=paragraphValue(value);
  writeExamples(storage,{...saved,topics:{...saved.topics,[topic.id]:paragraph}});
  return paragraph;
}
export function addExample(title,value,storage,id=`custom-${crypto.randomUUID()}`){
  if(typeof title!=='string'||!title.trim()||title.trim().length>120)throw new Error('Enter a title of at most 120 characters.');
  if(!validExample(value)||!value.romanized.trim())throw new Error('Enter Romanized text for the example.');
  const saved=savedExamples(storage),custom=saved.customTopics??[];
  if(!/^custom-[a-z0-9-]{1,80}$/.test(id)||Object.hasOwn(saved.topics,id)||custom.some(topic=>topic.id===id))throw new Error('This example could not be saved.');
  const topic={id,title:title.trim(),custom:true},paragraph=paragraphValue(value);
  writeExamples(storage,{...saved,customTopics:[...custom,{id,title:topic.title}],topics:{...saved.topics,[id]:paragraph}});
  return {topic,paragraph};
}
function validExampleEdit(previous,text,edit){
  return edit&&[edit.start,edit.oldEnd,edit.newEnd].every(Number.isInteger)
    &&edit.start>=0&&edit.oldEnd>=edit.start&&edit.newEnd>=edit.start
    &&edit.oldEnd<=previous.romanized.length&&edit.newEnd<=text.length
    &&previous.romanized.slice(0,edit.start)===text.slice(0,edit.start)
    &&previous.romanized.slice(edit.oldEnd)===text.slice(edit.newEnd);
}
function retainedSpans(previous,text,edit){
  let start=0,oldEnd=previous.romanized.length,newEnd=text.length;
  if(validExampleEdit(previous,text,edit))({start,oldEnd,newEnd}=edit);
  else{
    while(start<oldEnd&&start<newEnd&&previous.romanized[start]===text[start])start++;
    while(oldEnd>start&&newEnd>start&&previous.romanized[oldEnd-1]===text[newEnd-1]){oldEnd--;newEnd--;}
  }
  const shift=newEnd-oldEnd;
  return previous.spans.flatMap(span=>span.end<=start?[span]:span.start>=oldEnd?[{...span,start:span.start+shift,end:span.end+shift}]:[]);
}
// beforeinput identifies the edited occurrence even when adjacent words repeat.
// Validate it against the resulting text; native caret positions also cover
// insertion/deletion events whose beforeinput data is unavailable (e.g. undo).
export function trackExampleInput(previous,text,before,start,end=start){
  // Canceled composition and identical replacements do not invalidate choices.
  if(text===previous.romanized)return previous;
  const delta=text.length-previous.romanized.length;
  const range=(from,to,after=to+delta)=>{
    const edit={start:from,oldEnd:to,newEnd:after};return validExampleEdit(previous,text,edit)?edit:null;
  };
  let edit=null;
  if(before?.text===previous.romanized){
    const history=/^history/.test(before.inputType??'');
    if(!history&&(before.start!==before.end||/^insert/.test(before.inputType??'')))edit=range(before.start,before.end);
    else if(!history&&delta<0){
      if(/Backward$/.test(before.inputType??''))edit=range(before.end+delta,before.end);
      else if(/Forward$/.test(before.inputType??''))edit=range(before.start,before.start-delta);
    }
  }
  if(!edit&&start===end){
    if(delta>0)edit=range(end-delta,end-delta,end);
    else if(delta<0)edit=range(start,start-delta,start);
  }
  return {...previous,romanized:text,spans:retainedSpans(previous,text,edit)};
}
function exampleTokens(example){
  const retained=new Map(example.spans.map(span=>[span.start,span])),tokens=[];let cursor=0;
  const matches=[...example.romanized.matchAll(inputWords)],ends=new Set(matches.map(match=>match.index+match[0].length));
  for(const match of matches){
    if(match.index<cursor)continue;
    const start=match.index,end=start+match[0].length,span=retained.get(start);
    // Multiword choices must still end at a complete token, not an edited prefix.
    const intact=span&&span.end>=end&&ends.has(span.end)&&example.romanized.slice(start,span.end)===span.input;
    const token=intact?{start,end:span.end,input:span.input,word:span.word}:{start,end,input:match[0]};
    tokens.push(token);cursor=token.end;
  }
  return tokens;
}
function composeExample(romanized,tokens){
  const spans=[],parts=[],unknown=[];let cursor=0,wasConverted=false;
  const punctuation=(text,start)=>text.replace(/\./g,(value,index)=>/\d/.test(romanized[start+index-1]??'')&&/\d/.test(romanized[start+index+1]??'')?value:'។');
  for(const token of tokens){
    const {start,end,input,word}=token,gap=romanized.slice(cursor,start);
    parts.push({text:wasConverted&&word&&gap===' '?'':punctuation(gap,cursor)},{text:word??input,token});
    if(word)spans.push({start,end,input,word});else unknown.push(input);
    wasConverted=!!word;cursor=end;
  }
  parts.push({text:punctuation(romanized.slice(cursor),cursor)});
  return {value:{romanized,khmer:parts.map(part=>part.text).join(''),spans,unknown},parts};
}
export function exampleChanged(value,saved){
  const choices=example=>example.spans.map(({start,end,input,word})=>[start,end,input,word]);
  return value.romanized!==saved.romanized||value.khmer!==saved.khmer||JSON.stringify(choices(value))!==JSON.stringify(choices(saved));
}
export function exampleWordAt(example,start,end=start){
  if(!Number.isInteger(start)||!Number.isInteger(end)||start<0||end<start||end>example.romanized.length)return null;
  return exampleTokens(example).find(token=>start>=token.start&&start<=token.end&&end<=token.end)??null;
}
export function exampleDisplayParts(example,language){
  const tokens=exampleTokens(example);
  if(language==='khmer'){
    const composed=composeExample(example.romanized,tokens);
    return composed.value.khmer===example.khmer?composed.parts:[{text:example.khmer}];
  }
  const parts=[];let cursor=0;
  for(const token of tokens){parts.push({text:example.romanized.slice(cursor,token.start)},{text:token.input,token});cursor=token.end;}
  parts.push({text:example.romanized.slice(cursor)});return parts;
}
// Shared paragraph view for saved examples and the free-form Typing converter.
export function renderParagraph({element,draft,language,identity,engine,selected,disabled=false,suggestionsId,onSelect,el,textField=false}){
  if(textField){
    const text=language==='khmer'?draft.khmer:draft.romanized;
    if(element.value!==text)element.value=text;
    return;
  }
  if(element.exampleDraft!==draft||element.exampleTopic!==identity||element.exampleEngine!==engine){
    element.replaceChildren();element.exampleDraft=draft;element.exampleTopic=identity;element.exampleEngine=engine;
    for(const part of exampleDisplayParts(draft,language)){
      if(!part.text)continue;
      const selectable=part.token&&engine,node=el(selectable?'button':'span',part.text,selectable?'example-word':undefined);
      if(selectable){node.type='button';node.exampleToken=part.token;node.setAttribute('aria-controls',suggestionsId);node.onclick=()=>onSelect(part.token);}
      element.append(node);
    }
  }
  for(const node of element.children)if(node.exampleToken){
    const token=node.exampleToken;node.disabled=disabled;
    node.setAttribute('aria-pressed',String(selected?.start===token.start&&selected?.end===token.end));
    node.title=t('Choose a suggestion for {input}',{input:token.input});
  }
}
export function paragraphWordAt(draft,language,start,end=start){
  if(language==='romanized')return exampleWordAt(draft,start,end);
  let offset=0;
  for(const part of exampleDisplayParts(draft,'khmer')){
    const next=offset+part.text.length;
    if(part.token&&start>=offset&&start<=next&&end<=next)return part.token;
    offset=next;
  }
  return null;
}
